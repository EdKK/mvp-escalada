"""End-to-end Fingerboard on generated Student.html and simulated local Apps Script."""
from pathlib import Path
import shutil
import subprocess
from playwright.sync_api import sync_playwright, expect

root = Path(__file__).resolve().parents[1]
server = subprocess.Popen(['node', 'tests/helpers/coach-browser-server.cjs'], cwd=root, stdout=subprocess.PIPE, text=True)
try:
    port = server.stdout.readline().strip()
    assert port.isdigit()
    base = 'http://127.0.0.1:' + port
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(headless=True, executable_path=shutil.which('chromium') or playwright.chromium.executable_path)
        context = browser.new_context(viewport={'width': 1440, 'height': 1000})
        context.route('**/*', lambda route: route.continue_() if route.request.url.startswith(base) else route.abort())
        errors = []
        context.on('page', lambda page: page.on('pageerror', lambda error: errors.append(str(error))))
        coach = context.new_page()

        def login_coach():
            coach.goto(base)
            coach.locator('#btnLogin').click()
            coach.locator('#btnFinishLogin').click()
            expect(coach.locator('#appPanel')).to_be_visible()

        login_coach()
        coach.locator('#coachAluno').select_option('s1')
        coach.locator('#coachData').fill('2026-11-26')
        coach.locator('#btnCriarTreino').click()
        expect(coach.locator('#previewTreinoAluno')).to_contain_text('2026-11-26')
        coach.locator('#libraryClassification').select_option('directed')
        expect(coach.locator('#libraryPanel')).to_be_visible()
        coach.locator('#directedSubblock').select_option('fingerboard')
        expect(coach.locator('#libraryPanel')).to_be_hidden()
        expect(coach.locator('#fbLoad')).to_have_value('bodyweight')
        coach.locator('#btnAddItem').click()
        expect(coach.locator('#fbModality')).to_be_focused()
        coach.locator('#fbModality').select_option('isometric')
        coach.locator('#fbGrip').select_option('edge')
        coach.locator('#fbGripOption').select_option('1.0')
        coach.locator('#fbPrehension').select_option('half')
        coach.locator('#fbGrip').select_option('sloper')
        expect(coach.locator('#fbPrehension')).to_be_hidden()
        expect(coach.locator('#fbPrehension')).to_have_value('')
        expect(coach.locator('#fbGripOption')).to_have_value('')
        coach.locator('#fbGripOption').select_option('level2')
        coach.locator('#fbSide').select_option('bilateral')
        coach.locator('#fbLoad').select_option('added')
        coach.locator('#fbKilograms').select_option('4')
        coach.locator('#fbLoad').select_option('assisted')
        expect(coach.locator('#fbKilograms')).to_have_value('')
        coach.locator('#fbAssistance').select_option('band')
        coach.locator('#fbSets').fill('2')
        coach.locator('#fbRepetitions').fill('3')
        coach.locator('#fbDuration').fill('5')
        coach.locator('#fbRepetitionRest').select_option('10')
        coach.locator('#fbSeriesRest').select_option(label='2')
        coach.locator('#itemNotas').fill('Preserve a posição dos ombros.')
        expect(coach.locator('#fbVolume')).to_contain_text('30 s de suspensão')
        for width in [390, 1024]:
            coach.set_viewport_size({'width': width, 'height': 1000})
            assert coach.evaluate('document.documentElement.scrollWidth <= innerWidth')
        print('PASS: legacy directed flow remains available; Fingerboard switches active fields, validates and calculates volume')

        coach.request.post(base+'/test-control', data={'failTable': 'PRESCRICAO_SERIES'})
        coach.locator('#btnAddItem').click()
        expect(coach.locator('#librarySaveHint')).to_contain_text('INTERNAL_ERROR')
        login_coach()
        coach.locator('#pendingCoachSaves button').click()
        expect(coach.locator('#previewTreinoAluno')).to_contain_text('Suspensão isométrica')
        expect(coach.locator('#previewTreinoAluno')).to_contain_text('Entre séries: 2 min')
        expect(coach.locator('#previewTreinoAluno .coach-exercise')).to_have_count(1)
        tables = coach.request.post(base+'/test-tables', data={}).json()
        assert len(tables['Items']) == 2 and len(tables['PRESCRICAO_SERIES']) == 3
        print('PASS: reload exposes the interrupted save and resumes the same item and series')

        student = context.new_page()
        student.set_viewport_size({'width': 390, 'height': 820})
        student.goto(base+'/student')
        student.evaluate("window.testProfile='student'")
        student.locator('#prepareLogin').click()
        student.locator('#finishLogin').click()
        student.locator('#days button[data-date="2026-11-26"]').click()
        card = student.locator('.exercise')
        for detail in ['Suspensão isométrica', 'Abaulado', 'Nível 2', 'Bilateral simultânea', 'Elástico',
                       '3 por série × 5 s', '30 s de suspensão', '10 s', '2 min', 'Preserve a posição dos ombros.']:
            expect(card).to_contain_text(detail)
        expect(card.locator('.rest-row')).to_have_count(1)
        expect(card.locator('.rest-value')).to_have_text('00:10')
        assert student.evaluate('document.documentElement.scrollWidth <= innerWidth')
        card.locator('.complete-btn').click()
        student.locator('#confirmComplete').click()
        expect(card).to_contain_text('30 s de suspensão')
        expect(card.locator('.saved-note').first).to_contain_text('2 séries')
        print('PASS: student sees every applicable parameter, uses the existing countdown and completes the prescribed dose')

        card.locator('.feedback-btn').click()
        student.locator('#feedbackStatus').select_option('partial')
        student.locator('#actual-0-repetitions').fill('1')
        student.locator('#actual-0-seconds').fill('6')
        student.locator('#actual-1-repetitions').fill('0')
        student.locator('#actual-1-seconds').fill('2.5')
        student.locator('#feedbackPain').fill('3')
        student.locator('#feedbackComment').fill('Inclui tentativa incompleta.')
        student.locator('#saveFeedback').click()
        expect(student.locator('#feedbackDialog')).to_be_hidden()
        expect(card).to_contain_text('8.5 s de suspensão')
        card.locator('.feedback-btn').click()
        expect(student.locator('#actual-1-repetitions')).to_have_value('0')
        expect(student.locator('#actual-1-seconds')).to_have_value('2.5')
        student.locator('#feedbackStatus').select_option('not_done')
        expect(student.locator('#actualSeriesFields')).to_be_hidden()
        student.locator('#saveFeedback').click()
        expect(card.locator('.saved-note').first).to_contain_text('0 s de suspensão')
        coach.get_by_role('button', name='Atualizar treinos', exact=True).click()
        expect(coach.locator('#listaRetornos')).to_contain_text('Série 2: 0 repetições / 2.5 s')
        expect(coach.locator('#listaRetornos')).to_contain_text('Quantidade executada: 0 s de suspensão')
        expect(coach.locator('#listaRetornos')).to_contain_text('Inclui tentativa incompleta.')
        print('PASS: partial time includes incomplete efforts, revisions reopen with zero and feedback returns to trainer')

        coach.get_by_role('button', name='Editar Fingerboard').click()
        expect(coach.locator('#fbGripOption')).to_have_value('level2')
        expect(coach.locator('#fbDuration')).to_have_value('5')
        coach.locator('#fbModality').select_option('pull')
        expect(coach.locator('#fbDuration')).to_have_value('')
        coach.locator('#fbRepetitions').fill('1')
        expect(coach.locator('#fbRepetitionRest')).to_be_hidden()
        expect(coach.locator('#fbRepetitionRest')).to_have_value('')
        coach.locator('#fbSide').select_option('right')
        coach.locator('#btnAddItem').click()
        expect(coach.locator('#previewTreinoAluno')).to_contain_text('Tração dos membros superiores')
        expect(coach.locator('#previewTreinoAluno')).to_contain_text('Revisão 2')
        expect(coach.locator('#previewTreinoAluno .coach-exercise')).to_have_count(1)
        student.locator('#refreshWorkouts').click()
        expect(card).to_contain_text('Tração dos membros superiores')
        expect(card.locator('.rest-value')).to_have_text('02:00')
        card.locator('.feedback-btn').click()
        student.locator('#feedbackStatus').select_option('partial')
        expect(student.locator('#actualSeriesFields input')).to_have_count(2)
        student.locator('#actual-0-repetitions').fill('1')
        student.locator('#actual-1-repetitions').fill('0')
        student.locator('#saveFeedback').click()
        expect(card.locator('.saved-note').first).to_contain_text('1 repetição')
        assert not errors, errors
        print('PASS: edit saves a revision on the same item, traction has no duration and accepts only repetitions')
        browser.close()
finally:
    server.terminate()
    server.wait(timeout=10)
